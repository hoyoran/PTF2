    fun getString(key: String, languageCode: String): String {
        val resolvedLang = resolveLanguage(languageCode)
        val defaultMap = translations[AppLanguage.ZH] ?: emptyMap()
        val langMap = translations[resolvedLang] ?: defaultMap
        return langMap[key] ?: defaultMap[key] ?: key
    }

    fun resolveLanguage(languageCode: String): AppLanguage {
        if (languageCode.lowercase() == "system") {
            val sysLanguage = Locale.getDefault().language.lowercase()
            return when {
                sysLanguage.startsWith("zh") -> AppLanguage.ZH
                sysLanguage.startsWith("ja") -> AppLanguage.JA
                sysLanguage.startsWith("ru") -> AppLanguage.RU
                else -> AppLanguage.EN
            }
        }
        return AppLanguage.fromCode(languageCode)
    }
}

val LocalAppLanguage = staticCompositionLocalOf { "SYSTEM" }

@Composable
@ReadOnlyComposable
fun stringResource(key: String): String {
    val languageCode = LocalAppLanguage.current
    return LanguageManager.getString(key, languageCode)
}
